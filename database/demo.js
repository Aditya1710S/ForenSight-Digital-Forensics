'use strict';
// Creates clearly marked SYNTHETIC records. Only runs when DEMO_MODE=true.
const fs = require('fs');
const sharp = require('sharp');
const { getDb } = require('./init');
const { newId } = require('../utils/ids');
const evidenceService = require('../services/evidenceService');
const audit = require('../services/auditService');

async function seedDemo() {
  const db = getDb();
  if (db.prepare('SELECT COUNT(*) c FROM cases WHERE is_demo = 1').get().c > 0) return false;
  const now = new Date().toISOString();
  const mk = (title, description, status, priority) => {
    const id = newId('CASE');
    db.prepare('INSERT INTO cases(id,title,description,investigator,status,priority,is_demo,created_at,updated_at) VALUES(?,?,?,?,?,?,1,?,?)').run(id, title, description, 'demo-analyst', status, priority, now, now);
    audit.record({ caseId: id, type: 'case.created', actor: 'demo-seed', description: `[DEMO] Synthetic case "${title}" created by DEMO_MODE.` });
    return id;
  };
  const c1 = mk('[DEMO] Synthetic image metadata review', 'DEMONSTRATION DATA. Synthetic image generated by ForenSight. Not genuine evidence.', 'In Progress', 'Medium');
  mk('[DEMO] Empty case for upload practice', 'DEMONSTRATION DATA. Use this case to practise uploading evidence.', 'Open', 'Low');
  const tmp = evidenceService.tmpName('.upload');
  await sharp({ create: { width: 640, height: 400, channels: 3, background: { r: 30, g: 70, b: 120 } } })
    .composite([{ input: Buffer.from('<svg width="640" height="400"><text x="40" y="210" font-size="40" fill="#fff" font-family="sans-serif">DEMO - SYNTHETIC IMAGE</text></svg>') }])
    .withExif({ IFD0: { Make: 'DEMO CAMERA', Model: 'Synthetic-1', Software: 'ForenSight demo seed' } }).jpeg().toFile(tmp);
  await evidenceService.ingest({ tempPath: tmp, originalName: 'demo-synthetic.jpg', declaredExt: '.jpg', declaredFormat: 'jpeg', detected: { category: 'image', format: 'jpeg', mime: 'image/jpeg', ext: '.jpg' }, caseId: c1, notes: 'DEMONSTRATION RECORD - synthetic, not genuine evidence.', actor: 'demo-seed', isDemo: 1 });
  return true;
}
module.exports = { seedDemo };
